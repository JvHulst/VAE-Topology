"""
Which images to pin, and to what, for the two MNIST experiments.

These anchors carry no heuristic at all, which is the point. An anchor image is
generated by applying a *known* group element to a canonical exemplar, so its
true latent coordinate is known exactly rather than estimated: rotate a digit by
exactly 90° and its θ is exactly 90°.

Only the periodic coordinates are anchored. The Gaussian subspace of
``MixedCircleVAE`` and ``MixedTorusVAE`` carries digit identity and style, and
is deliberately left to organise itself under reconstruction pressure alone —
anchoring it would require deciding in advance where each digit belongs.

``inspect_anchors`` writes a thumbnail grid of the chosen images with their
targets, which is the quickest way to catch an anchor set that is wrong.

Author: Jilles van Hulst
"""

import os

import matplotlib.pyplot as plt
import numpy as np


def find_canonical_circle_anchors(data, target_angles=None, anchor_digits=None):
    """
    Find canonical anchor points for rotated MNIST.

    For each target angle and each digit in anchor_digits, one training sample
    is selected: the one whose rotation angle is closest to the target.  Only
    the S¹ coordinate theta is constrained; the Gaussian style dimensions z_d
    are never touched (subset anchoring).

    Anchoring all digit classes at every target angle gives stronger, more
    uniform coverage of S¹ than anchoring a single digit, and the style space
    still self-organises completely freely through reconstruction pressure.

    Args:
        data: dict with 'theta' and 'labels' arrays.
        target_angles: 1D array of target angles in (-pi, pi].
                       Defaults to 8 evenly spaced angles.
        anchor_digits: List of digit classes to anchor at each target angle.
                       Defaults to all unique classes present in data['labels'].
                       Pass a single-element list to anchor only one digit class.

    Returns:
        (anchor_indices, anchor_targets)
        anchor_indices: list of integer indices into data arrays.
        anchor_targets: dict with a 'theta' list.
    """
    if target_angles is None:
        target_angles = np.linspace(-np.pi, np.pi, 8, endpoint=False)

    if anchor_digits is None:
        if 'labels' not in data:
            anchor_digits = [None]
        else:
            anchor_digits = sorted(np.unique(data['labels']).tolist())
    else:
        if 'labels' not in data:
            raise ValueError("anchor_digits requires 'labels' in data dict.")

    anchor_indices = []
    target_list = []
    seen = set()

    for t in target_angles:
        for digit in anchor_digits:
            if digit is None:
                eligible_idx = np.arange(len(data['theta']))
            else:
                eligible_idx = np.where(data['labels'] == digit)[0]
                if len(eligible_idx) == 0:
                    continue

            theta_eligible = data['theta'][eligible_idx]
            dist = np.abs(np.angle(np.exp(1j * (theta_eligible - t))))
            local_idx = int(np.argmin(dist))
            global_idx = int(eligible_idx[local_idx])

            if global_idx not in seen:
                seen.add(global_idx)
                anchor_indices.append(global_idx)
                target_list.append(float(t))

    n_digits = len([d for d in anchor_digits if d is not None]) or 1
    print(f"  Selected {len(anchor_indices)} circle anchors  "
          f"({len(target_angles)} angles x {n_digits} digits).")
    return anchor_indices, {'theta': target_list}


def find_canonical_torus_anchors(data, pixel_shifts=None, anchor_digits=None):
    """
    Find canonical anchor points for shifted MNIST using exact integer pixel shifts.

    For each (dx, dy) target position and each digit in anchor_digits, one
    training sample is selected: the one whose (theta1, theta2) is closest to
    the target angles.  Anchoring all digit classes at every target position
    gives dense, uniform coverage of T² while keeping z_d completely free —
    only the periodic coordinates are ever constrained (subset anchoring).

    Args:
        data: dict with 'theta1', 'theta2', 'dx', 'dy', and 'labels' arrays.
        pixel_shifts: List of (dx, dy) integer pairs to use as anchor positions.
                      Defaults to a 3x3 grid: d in {0, 9, 19} for each axis,
                      giving three evenly spaced angles per dimension.
        anchor_digits: List of digit classes to anchor at each target position.
                       Defaults to all unique classes present in data['labels'].
                       Pass a single-element list to recover the old single-digit
                       behaviour.

    Returns:
        (anchor_indices, anchor_targets)
        anchor_indices: list of integer indices into data arrays.
        anchor_targets: dict with 'theta1' and 'theta2' lists.
    """
    if pixel_shifts is None:
        pixel_shifts = [(dx, dy)
                        for dx in [0, 9, 19]
                        for dy in [0, 9, 19]]

    def _shift_to_angle(d):
        return (2 * np.pi * d / 28 + np.pi) % (2 * np.pi) - np.pi

    if anchor_digits is None:
        if 'labels' not in data:
            # No label information: treat all samples as one group
            anchor_digits = [None]
        else:
            anchor_digits = sorted(np.unique(data['labels']).tolist())
    else:
        if 'labels' not in data:
            raise ValueError("anchor_digits requires 'labels' in data dict.")

    anchor_indices = []
    target_theta1 = []
    target_theta2 = []
    seen = set()

    for dx, dy in pixel_shifts:
        target_t1 = _shift_to_angle(dx)
        target_t2 = _shift_to_angle(dy)

        for digit in anchor_digits:
            if digit is None:
                eligible_idx = np.arange(len(data['theta1']))
            else:
                eligible_idx = np.where(data['labels'] == digit)[0]
                if len(eligible_idx) == 0:
                    continue

            theta1_el = data['theta1'][eligible_idx]
            theta2_el = data['theta2'][eligible_idx]
            d1 = np.abs(np.angle(np.exp(1j * (theta1_el - target_t1))))
            d2 = np.abs(np.angle(np.exp(1j * (theta2_el - target_t2))))
            local_idx = int(np.argmin(d1 + d2))
            global_idx = int(eligible_idx[local_idx])

            if global_idx not in seen:
                seen.add(global_idx)
                anchor_indices.append(global_idx)
                target_theta1.append(target_t1)
                target_theta2.append(target_t2)

    n_digits = len([d for d in anchor_digits if d is not None]) or 1
    print(f"  Selected {len(anchor_indices)} torus anchors  "
          f"({len(pixel_shifts)} positions x {n_digits} digits).")
    return anchor_indices, {'theta1': target_theta1, 'theta2': target_theta2}


def inspect_anchors(data, anchor_indices, anchor_targets, save_path,
                    coord_names=('theta',)):
    """
    Save a thumbnail grid of anchor images with their target coordinates labelled.

    Provides a quick visual sanity-check that the selected anchor images are
    reasonable representatives of the target angles / shifts, and that the
    canonical-digit filtering has worked as intended.

    Args:
        data:           dict containing at least 'x' [N, 784] and, if
                        anchor_digits was used, 'labels' [N].
        anchor_indices: list of int indices into data (returned by
                        find_canonical_*_anchors).
        anchor_targets: dict mapping coordinate name(s) to lists of float
                        target values (returned by find_canonical_*_anchors).
        save_path:      File path for the output PNG (parent dir created if needed).
        coord_names:    Tuple of coordinate keys to read from anchor_targets and
                        display as sub-titles, e.g. ('theta',) or
                        ('theta1', 'theta2').

    Returns:
        None.  Saves a PNG to save_path and prints the path.
    """
    from .._style import apply_publication_style
    apply_publication_style()

    n = len(anchor_indices)
    ncols = min(n, 8)
    nrows = (n + ncols - 1) // ncols

    fig, axes = plt.subplots(nrows, ncols,
                             figsize=(ncols * 1.4, nrows * 1.8))
    axes = np.array(axes).reshape(nrows, ncols)

    has_labels = 'labels' in data

    for i, global_idx in enumerate(anchor_indices):
        row, col = divmod(i, ncols)
        ax = axes[row, col]
        img = data['x'][global_idx].reshape(28, 28)
        ax.imshow(img, cmap='gray', vmin=0, vmax=1)
        ax.axis('off')

        # Build subtitle from target coordinate values
        parts = []
        for cname in coord_names:
            if cname in anchor_targets:
                val = anchor_targets[cname][i]
                parts.append(f"{cname}={val:.2f}")
        if has_labels:
            parts.append(f"d={int(data['labels'][global_idx])}")
        ax.set_title('\n'.join(parts), fontsize=6)

    # Hide any unused axes
    for j in range(n, nrows * ncols):
        row, col = divmod(j, ncols)
        axes[row, col].axis('off')

    fig.suptitle(
        f"{n} anchors  |  digit filter: "
        f"{int(data['labels'][anchor_indices[0]]) if has_labels else 'none'}",
        fontsize=8, y=1.01)
    plt.tight_layout()

    os.makedirs(os.path.dirname(os.path.abspath(save_path)), exist_ok=True)
    fig.savefig(save_path, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f"  Anchor inspection grid saved to {save_path}")
